def _events():
    out = []
    for d, t, tz, kind in _RAW:
        y, m, dd = map(int, d.split("-"))
        if t:
            hh, mm = map(int, t.split(":"))
            local = datetime(y, m, dd, hh, mm, tzinfo=tz)
            jst = local.astimezone(JST)
            when = f"{jst:%m/%d}({'月火水木金土日'[jst.weekday()]}) {jst:%H:%M}"
        else:
            jst = datetime(y, m, dd, 12, 0, tzinfo=JST)
            when = f"{jst:%m/%d}({'月火水木金土日'[jst.weekday()]}) 昼ごろ"
        out.append({"kind": kind, "at": jst, "when": when, **INFO[kind]})
    return sorted(out, key=lambda e: e["at"])


EVENTS = _events()


def upcoming(days: int = 30, now: datetime | None = None) -> list[dict]:
    now = now or datetime.now(JST)
    start = now - timedelta(hours=3)  # 発表直後の数時間は「直後」として表示
    return [e for e in EVENTS if start <= e["at"] <= now + timedelta(days=days)]


def last_known() -> date:
    return EVENTS[-1]["at"].date()


def label(e: dict, now: datetime | None = None) -> str:
    now = now or datetime.now(JST)
    delta = (e["at"].date() - now.date()).days
    rel = {0: "今日", 1: "明日", 2: "あさって"}.get(delta, f"{delta}日後") if delta >= 0 else "発表直後"
    if e["at"] < now:
        rel = "発表直後"
    return f"{rel} {e['when']} {e['name']}"


